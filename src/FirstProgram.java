public class FirstProgram {
    static void main() {
        System.out.print("Hello World"); // only print method prints the output on same line
        System.out.println("4+6"); // Compiled as string
        System.out.println(4+6); // Compiled as expression
        System.out.println("hello bhai " + "Kha hai aaj kal ?"); // + act as concatenation operator

        // double slash allow us to make a single line comment.

    }
}
