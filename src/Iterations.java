public class Iterations {
    static void main() {
//        LOOPS --> WHILE
        int i =  1;
        while(i <= 5){ // boolean --> true / false
//            System.out.println(i);
            i++;
        }
//         DO WHILE
        do{
            System.out.println(i);
            i++;
        }while(i <= 10);

//        FOR LOOP
        for(int j = 1; j<= 5; j++){
            System.out.println(j);
        }
    }
}